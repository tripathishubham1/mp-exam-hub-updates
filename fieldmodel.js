/* MP Exam Hub on-device field model (runtime). Naive Bayes over label words, label character 3-grams,
   field-ID fragments, control type and option words. Runs fully offline; no data leaves the phone.
   The trained weights are attached as MPHubModel.data by fieldmodel-data.js (generated by tools/model/train.js). */
(function (root) {
  const norm = s => String(s || '').toLowerCase().replace(/[_*:：|()\[\]{}.,;!?'"/\\-]+/g, ' ').replace(/\s+/g, ' ').trim();
  function cidOf(id) {
    let c = String(id || '').split(/[$]/).pop(); const segs = c.split('_').filter(s => s && !/^\d+$/.test(s)); c = segs.length ? segs[segs.length - 1] : c;
    c = c.replace(/^(txt|txy|ddl|drp|rdo|rbl|rb|chk|fu|lbl|cmb|tb|hf|cbo|sel|dd|FU|TXT|DDL|RDO|RBL|DRP)(?=[A-Z0-9])/, '').replace(/^(txt|ddl|drp|rdo|rbl)/i, '');
    return c.toLowerCase().replace(/[^a-z0-9]/g, '').replace(/\d+$/, '');
  }
  /* function words that carry no meaning (Hindi + English) */
  const STOP = new Set('की का के है हैं में से को पर क्या आप अभ्यर्थी अभ्यर्थियों हेतु तथा एवं या और करें कृपया द्वारा लिए यदि तो वाले वाली गया गयी किया the of are you is do have has your for and or a an to in on by with as if please enter select candidate candidates'.split(' '));
  function features(ex) {
    const f = new Set(), lab = norm(ex.label), ctx = norm(ex.context || '').slice(0, 120);
    lab.split(' ').forEach(w => { if (w.length >= 2 && !STOP.has(w)) f.add('w:' + w); });
    const s = lab.replace(/\s+/g, '_'); for (let i = 0; i + 3 <= s.length; i++) f.add('c:' + s.slice(i, i + 3));
    ctx.split(' ').forEach(w => { if (w.length >= 3 && !STOP.has(w)) f.add('x:' + w); });
    const c = ex.cid != null ? ex.cid : cidOf(ex.id);
    if (c) { f.add('I:' + c); for (let i = 0; i + 4 <= c.length; i++) f.add('i:' + c.slice(i, i + 4)); }
    f.add('t:' + (ex.type || 'text'));
    (ex.options || []).slice(0, 8).forEach(o => norm(o).split(' ').forEach(w => { if (w.length >= 2 && !/select|चुनें/.test(w)) f.add('o:' + w); }));
    return [...f];
  }
  /* returns {key, p, margin} — key 'none' (or null) means: leave this field for the student */
  function predict(ex, data) {
    data = data || api.data; if (!data) return null;
    const fs = features(ex), scores = {};
    for (const k of data.classes) {
      let s = data.prior[k]; const cnt = data.counts[k] || {}, denom = Math.log(data.total[k] + data.alpha * data.vocab);
      for (const ft of fs) { if (!(ft in data.seen)) continue; s += Math.log((cnt[ft] || 0) + data.alpha) - denom; }
      scores[k] = s;
    }
    const ranked = Object.entries(scores).sort((a, b) => b[1] - a[1]);
    const max = ranked[0][1], z = ranked.reduce((t, [, v]) => t + Math.exp(v - max), 0);
    return { key: ranked[0][0], p: 1 / z, margin: ranked[0][1] - (ranked[1] ? ranked[1][1] : -Infinity), second: ranked[1] && ranked[1][0] };
  }
  /* nearest training example (cosine over binary features, idf-weighted) */
  function nearest(ex, data) {
    data = data || api.data; if (!data || !data.ex) return null;
    if (!data._fi) { data._fi = {}; data.feats.forEach((f, i) => data._fi[f] = i); }
    const q = features(ex).map(f => data._fi[f]).filter(i => i !== undefined); if (!q.length) return null;
    const qs = new Set(q), w = i => data.idf[i];
    const qn = Math.sqrt(q.reduce((t, i) => t + w(i) * w(i), 0));
    let best = null;
    for (const [k, fs] of data.ex) {
      let dot = 0, n = 0; for (const i of fs) { n += w(i) * w(i); if (qs.has(i)) dot += w(i) * w(i); }
      const sim = dot / (qn * Math.sqrt(n) || 1);
      if (!best || sim > best.sim) best = { key: data.classes[k], sim };
    }
    return best;
  }
  /* the agent only accepts confident answers on which both methods agree, and never "none" */
  function decide(ex, data) {
    data = data || api.data; const r = predict(ex, data);
    if (!r || r.key === 'none') return null;
    if (!(r.p >= (data.minP || 0.9) && r.margin >= (data.minMargin || 2))) return null;
    const nn = nearest(ex, data);
    if (nn && (nn.key !== r.key || nn.sim < (data.minSim || 0.3))) return null;
    return Object.assign(r, { sim: nn ? nn.sim : null });
  }
  const api = { features, predict, decide, nearest, cidOf, data: (root.MPHubModel && root.MPHubModel.data) || null };
  if (typeof module !== 'undefined' && module.exports) module.exports = api; else root.MPHubModel = api;
})(typeof window !== 'undefined' ? window : globalThis);
